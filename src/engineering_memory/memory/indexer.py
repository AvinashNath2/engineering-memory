"""Generated views: INDEX.md, PROJECTS.md, PEOPLE.md, people/*.md, and the optional SQLite FTS index.

Everything here is *derived* from the ticket Markdown and can be rebuilt at any time.
Output is deterministic (no timestamps) so regenerating does not create noisy Git diffs.
"""

from __future__ import annotations

import hashlib
import os
import sqlite3
from dataclasses import dataclass, field
from pathlib import Path

from ..store import atomic_write, parse_frontmatter, read_text, slugify
from .layout import iter_ticket_dirs, list_projects

GENERATED = "<!-- GENERATED by `memory index`. Do not edit; changes are overwritten. Source of truth: the ticket folders. -->"
MANUAL_MARK = "<!-- em:manual -->"
FTS_FILE = ".engineering-memory.sqlite"


def _esc(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _write_if_changed(path: Path, content: str) -> bool:
    if not content.endswith("\n"):
        content += "\n"
    if path.exists() and read_text(path) == content:
        return False
    atomic_write(path, content)
    return True


@dataclass
class TicketRow:
    ticket: str
    project: str
    title: str
    status: str
    updated: str
    branches: list[str]
    rel: str
    team: list[dict] = field(default_factory=list)


def collect_tickets(memory_dir: Path) -> list[TicketRow]:
    rows: list[TicketRow] = []
    for tdir in iter_ticket_dirs(memory_dir):
        mf = tdir / "MEMORY.md"
        if not mf.exists():
            continue
        try:
            meta, _ = parse_frontmatter(read_text(mf))
        except Exception:
            continue
        rows.append(
            TicketRow(
                ticket=str(meta.get("ticket", tdir.name)),
                project=str(meta.get("project", tdir.parent.parent.name)),
                title=str(meta.get("title", "unknown")),
                status=str(meta.get("status", "unknown")),
                updated=str(meta.get("updated", "")),
                branches=[str(b) for b in meta.get("branches") or []],
                rel=mf.relative_to(memory_dir).as_posix(),
                team=[m for m in meta.get("team") or [] if isinstance(m, dict)],
            )
        )
    return rows


def rebuild_index(memory_dir: Path) -> list[str]:
    """Regenerate INDEX.md, PROJECTS.md, PEOPLE.md and people/*.md. Returns files that changed."""
    rows = collect_tickets(memory_dir)
    projects = list_projects(memory_dir)
    changed: list[str] = []

    # ---- INDEX.md
    lines = [
        "# Engineering Memory Index", "", GENERATED, "",
        "Start here. Find the project and ticket, then read the ticket's `MEMORY.md`.",
        "See also: [PROJECTS](PROJECTS.md) · [PEOPLE](PEOPLE.md).", "",
        f"**{len(projects)}** project(s), **{len(rows)}** ticket memor{'y' if len(rows) == 1 else 'ies'}.", "",
    ]
    by_project: dict[str, list[TicketRow]] = {}
    for r in rows:
        by_project.setdefault(r.project, []).append(r)
    for slug in sorted(set(by_project) | {p.slug for p in projects}):
        lines += [f"## {slug}", ""]
        trs = sorted(by_project.get(slug, []), key=lambda r: r.ticket)
        if not trs:
            lines += ["_No tickets yet._", ""]
            continue
        lines += ["| Ticket | Title | Status | Updated | Branches |", "| --- | --- | --- | --- | --- |"]
        for r in trs:
            branches = ", ".join(f"`{b}`" for b in r.branches) or "—"
            lines.append(f"| [{r.ticket}]({r.rel}) | {_esc(r.title)} | {r.status} | {r.updated[:10]} | {branches} |")
        lines.append("")
    recent = sorted(rows, key=lambda r: (r.updated, r.ticket), reverse=True)[:10]
    if recent:
        lines += ["## Recently updated", ""]
        lines += [f"- {r.updated[:10]} — [{r.ticket}]({r.rel}) {_esc(r.title)}" for r in recent]
        lines.append("")
    decisions = sorted(p for p in (memory_dir / "decisions").glob("*.md"))
    if decisions:
        lines += ["## Cross-cutting decisions", ""]
        lines += [f"- [{p.stem}](decisions/{p.name})" for p in decisions]
        lines.append("")
    if _write_if_changed(memory_dir / "INDEX.md", "\n".join(lines)):
        changed.append("INDEX.md")

    # ---- PROJECTS.md
    pl = ["# Projects", "", GENERATED, ""]
    if projects:
        pl += ["| Project | Repositories | Ticket prefixes | Tickets |", "| --- | --- | --- | --- |"]
        for p in projects:
            repos = ", ".join(f"`{r.get('name')}`" for r in p.repos) or "—"
            pref = ", ".join(p.ticket_prefixes) or "—"
            pl.append(f"| [{_esc(p.name)}](projects/{p.slug}/PROJECT.md) | {repos} | {pref} | {len(by_project.get(p.slug, []))} |")
    else:
        pl.append("_No projects registered. Run `memory project add`._")
    if _write_if_changed(memory_dir / "PROJECTS.md", "\n".join(pl)):
        changed.append("PROJECTS.md")

    # ---- PEOPLE.md + people/*.md
    people: dict[str, dict] = {}
    for r in rows:
        for m in r.team:
            name = str(m.get("name", "")).strip()
            if not name:
                continue
            rec = people.setdefault(name.lower(), {"name": name, "roles": {}, "tickets": {}})
            role = str(m.get("role", "unknown"))
            rec["roles"].setdefault(role, 0)
            rec["roles"][role] += 1
            rec["tickets"].setdefault(r.ticket, []).append((role, m.get("confidence", "unconfirmed"), m.get("source", "")))
    pp = ["# People", "", GENERATED, "", "Only people and roles stated in sources are listed. Role `unknown` means no source stated it.", ""]
    if people:
        pp += ["| Name | Roles | Tickets |", "| --- | --- | --- |"]
        for key in sorted(people):
            rec = people[key]
            slug = slugify(rec["name"])
            tickets = ", ".join(sorted(rec["tickets"]))
            pp.append(f"| [{_esc(rec['name'])}](people/{slug}.md) | {_esc(', '.join(sorted(rec['roles'])))} | {tickets} |")
    else:
        pp.append("_No people recorded yet._")
    if _write_if_changed(memory_dir / "PEOPLE.md", "\n".join(pp)):
        changed.append("PEOPLE.md")
    rel_for = {r.ticket: r.rel for r in rows}
    for key, rec in people.items():
        slug = slugify(rec["name"])
        path = memory_dir / "people" / f"{slug}.md"
        manual = "\n## Notes\n\n_Add personal notes below; they are preserved when the index is rebuilt._\n"
        if path.exists():
            old = read_text(path)
            if MANUAL_MARK in old:
                manual = old.split(MANUAL_MARK, 1)[1].rstrip("\n") + "\n"
        body = [f"# {rec['name']}", "", GENERATED, "", "## Involvement", ""]
        for t in sorted(rec["tickets"]):
            for role, conf, src in rec["tickets"][t]:
                srcs = f" _(source: {src})_" if src else ""
                body.append(f"- [{t}](../{rel_for.get(t, '')}) — {role} [{conf}]{srcs}")
        content = "\n".join(body) + "\n\n" + MANUAL_MARK + manual
        if _write_if_changed(path, content):
            changed.append(f"people/{slug}.md")
    return changed



# ---- optional SQLite FTS5 index ----------------------------------------
def _walk_md(memory_dir: Path):
    for root, dirs, files in os.walk(memory_dir):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for f in sorted(files):
            if f.endswith(".md"):
                yield Path(root) / f


def signature(memory_dir: Path) -> str:
    h = hashlib.sha1()
    for p in _walk_md(memory_dir):
        st = p.stat()
        h.update(f"{p.relative_to(memory_dir)}|{st.st_size}|{int(st.st_mtime)}".encode())
    return h.hexdigest()


def fts_available() -> bool:
    try:
        con = sqlite3.connect(":memory:")
        con.execute("create virtual table t using fts5(a)")
        con.close()
        return True
    except sqlite3.Error:
        return False


def build_fts(memory_dir: Path) -> int:
    """(Re)build the rebuildable SQLite FTS5 index. Returns number of documents indexed."""
    if not fts_available():
        raise RuntimeError("This Python's SQLite was built without FTS5; text search still works.")
    db = memory_dir / FTS_FILE
    tmp = memory_dir / (FTS_FILE + ".tmp")
    if tmp.exists():
        tmp.unlink()
    con = sqlite3.connect(tmp)
    con.execute("create virtual table docs using fts5(path unindexed, title, body, tokenize='unicode61')")
    con.execute("create table meta(key text primary key, value text)")
    n = 0
    for p in _walk_md(memory_dir):
        rel = p.relative_to(memory_dir).as_posix()
        text = read_text(p)
        con.execute("insert into docs(path,title,body) values(?,?,?)", (rel, rel, text))
        n += 1
    con.execute("insert into meta values('signature', ?)", (signature(memory_dir),))
    con.commit()
    con.close()
    os.replace(tmp, db)
    return n


def fts_is_fresh(memory_dir: Path) -> bool:
    db = memory_dir / FTS_FILE
    if not db.exists():
        return False
    try:
        con = sqlite3.connect(db)
        row = con.execute("select value from meta where key='signature'").fetchone()
        con.close()
    except sqlite3.Error:
        return False
    return bool(row) and row[0] == signature(memory_dir)
